def translate(cell):
    key = cell.strip()
    return TRANSLATIONS.get(key, key)


with open(DATASET_IN, newline="", encoding="utf-8") as fin, \
     open(DATASET_OUT, "w", newline="", encoding="utf-8") as fout:
    reader = csv.reader(fin)
    writer = csv.writer(fout)
    writer.writerow(next(reader))
    for row in reader:
        writer.writerow([translate(cell) for cell in row])

with open(SEVERITY_IN, newline="", encoding="utf-8") as fin, \
     open(SEVERITY_OUT, "w", newline="", encoding="utf-8") as fout:
    reader = csv.reader(fin)
    writer = csv.writer(fout)
    writer.writerow(next(reader))
    for row in reader:
        if row:
            row[0] = translate(row[0])
        writer.writerow(row)

